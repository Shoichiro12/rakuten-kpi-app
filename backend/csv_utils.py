"""CSVエクスポート共通ユーティリティ。

`csv_safe_cell()` はCSVインジェクション（数式注入・CWE-1236）対策。商品名・ジャンル名など
自由入力由来の文字列セルをエクスポートするときに必ず通す（マスタCRUD規約参照）。
"""


def csv_safe_cell(v):
    """文字列セルがExcel/Googleスプレッドシートで数式扱いされないよう無害化する。

    先頭が `=` `+` `-` `@` タブ・CR のいずれかならシングルクォートを1つ前置する（OWASP推奨）。
    対象は `str` のみ（数値・None・空文字はそのまま返す。負数の数値セルを誤って
    壊さないためのガード）。
    """
    if not isinstance(v, str) or not v:
        return v
    if v[0] in ("=", "+", "-", "@", "\t", "\r", "\n"):
        return "'" + v
    return v
